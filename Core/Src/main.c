void Framebuffer_Fill(void)
{
    volatile uint32_t *fb =
        (volatile uint32_t *)FB_ADDR;

    for (uint32_t y = 0; y < LCD_H; y++)
    {
        for (uint32_t x = 0; x < LCD_W; x++)
        {
            uint32_t color;

            if (x < LCD_W / 3)
                color = 0xFFFF0000; // Red
            else if (x < 2 * LCD_W / 3)
                color = 0xFF00FF00; // Green
            else
                color = 0xFF0000FF; // Blue

            fb[y * LCD_W + x] = color;
        }
    }
}


