void paint_all_black(uint32_t * const sdram_ptr) {
  for (uint32_t y = 0; y < LCD_H; y++)
  {
	for (uint32_t x = 0; x < LCD_W; x++)
	{
	  sdram_ptr[y * LCD_W + x] = COLOR_BLACK;
	}
  }
}


void paint_dot(uint32_t * const sdram_ptr, uint16_t x_pos, uint16_t y_pos) {

  if(x_pos >= LCD_W || y_pos >= LCD_H) {
    return;
  }

  sdram_ptr[y_pos * LCD_W + x_pos] = COLOR_WHITE;

}

void put_dot(uint32_t * const sdram_ptr, uint16_t x_pos, uint16_t y_pos, uint16_t diam, uint32_t color) {

  if(x_pos >= LCD_W || y_pos >= LCD_H) {
    return;
  }

  // put the new dot with the specified diameter
  for (uint16_t dy = 0; dy < diam; dy++) {
    for (uint16_t dx = 0; dx < diam; dx++) {
      uint16_t px = x_pos + dx;
      uint16_t py = y_pos + dy;
      if (px < LCD_W && py < LCD_H) {
        sdram_ptr[py * LCD_W + px] = color;
      }
    }
  }

}

void move_dot(uint32_t * const sdram_ptr, uint16_t new_x, uint16_t new_y, uint32_t color) {
  static uint16_t last_x = 0xFFFF;
  static uint16_t last_y = 0xFFFF;

  if(last_x < LCD_W && last_y < LCD_H) {
    put_dot(sdram_ptr, last_x, last_y, 20, COLOR_BLACK);
  }

  put_dot(sdram_ptr, new_x, new_y, 20, color);
  last_x = new_x;
  last_y = new_y;

}


void put_char(volatile uint32_t * const sdram_ptr, uint16_t x_pos,
              uint16_t y_pos, char c, uint32_t color) {
  put_char_scaled(sdram_ptr, x_pos, y_pos, c, color, 1U);
}


void put_char_scaled(volatile uint32_t * const sdram_ptr, uint16_t x_pos,
                     uint16_t y_pos, char c, uint32_t color, uint8_t scale) {
  if (sdram_ptr == NULL || scale == 0U || x_pos >= LCD_W || y_pos >= LCD_H) {
    return;
  }

  uint8_t character = (uint8_t)c;
  if (character < FONT_FIRST_CHAR || character > FONT_LAST_CHAR) {
    character = (uint8_t)'?';
  }
  const uint8_t *glyph = font8x8[character - FONT_FIRST_CHAR];

  for (uint32_t row = 0U; row < FONT_HEIGHT; row++) {
    const uint32_t y = (uint32_t)y_pos + row * scale;
    if (y >= LCD_H) {
      break;
    }

    for (uint32_t column = 0U; column < FONT_WIDTH; column++) {
      const uint32_t x = (uint32_t)x_pos + column * scale;
      if (x >= LCD_W) {
        break;
      }
      if ((glyph[row] & (0x80U >> column)) == 0U) {
        continue;
      }

      /* Enlarge each lit font pixel into a scale-by-scale square. Use 32-bit
         coordinates so clipping also works for large positions and scales. */
      for (uint32_t dy = 0U; dy < scale && y + dy < LCD_H; dy++) {
        volatile uint32_t *destination = &sdram_ptr[(y + dy) * LCD_W + x];
        for (uint32_t dx = 0U; dx < scale && x + dx < LCD_W; dx++) {
          destination[dx] = color;
        }
      }
    }
  }
}
